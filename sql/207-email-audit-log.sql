create table email_audit_log (
	auditid bigint generated by default as identity primary key,
	occurred_at timestamp with time zone not null default now(),
	action text not null,
	actor varchar(20) not null,
	ip_addr varchar(64) null,
	where_path text not null,
	how varchar(32) not null,
	status varchar(16) not null,
	recipient text not null,
	subject text not null,
	details text not null,
	issue_key text null,
	issue_state varchar(16) not null default 'none',
	deptcode text null,
	scannercode text null,
	researchercode text null,
	requestercode text null
);

alter table email_audit_log
	add constraint email_audit_log_valid_status
	check (status in ('sent', 'failed', 'resolved', 'skipped'));

alter table email_audit_log
	add constraint email_audit_log_valid_issue_state
	check (issue_state in ('none', 'open', 'resolved'));

create index email_audit_log_occurred_at_idx
	on email_audit_log (occurred_at desc);

create index email_audit_log_status_idx
	on email_audit_log (status);

create index email_audit_log_issue_state_idx
	on email_audit_log (issue_state);

create index email_audit_log_issue_key_idx
	on email_audit_log (issue_key);

create index email_audit_log_dept_idx
	on email_audit_log (deptcode);

create index email_audit_log_scanner_idx
	on email_audit_log (scannercode);

create index email_audit_log_researcher_idx
	on email_audit_log (researchercode);

create index email_audit_log_requester_idx
	on email_audit_log (requestercode);

comment on table email_audit_log is 'Email delivery and notification-issue lifecycle feed for admin diagnostics.';
comment on column email_audit_log.action is 'Email action identifier, for example email.scheduler.notification.';
comment on column email_audit_log.actor is 'Authenticated user that triggered the action, or system.';
comment on column email_audit_log.where_path is 'Origin route path for the email action.';
comment on column email_audit_log.status is 'Email event status: sent, failed, resolved, skipped.';
comment on column email_audit_log.issue_key is 'Optional stable key used to track an actionable notification issue lifecycle.';
comment on column email_audit_log.issue_state is 'Issue lifecycle state: none, open, resolved.';
