create table rbac_audit_log (
	auditid bigint generated by default as identity primary key,
	occurred_at timestamp with time zone not null default now(),
	action text not null,
	actor varchar(20) not null,
	where_path text not null,
	how varchar(32) not null,
	what text not null,
	deptcode text null,
	scannercode text null,
	researchercode text null,
	requestercode text null
);

create index rbac_audit_log_occurred_at_idx
	on rbac_audit_log (occurred_at desc);

create index rbac_audit_log_action_idx
	on rbac_audit_log (action);

create index rbac_audit_log_dept_idx
	on rbac_audit_log (deptcode);

create index rbac_audit_log_scanner_idx
	on rbac_audit_log (scannercode);

create index rbac_audit_log_researcher_idx
	on rbac_audit_log (researchercode);

create index rbac_audit_log_requester_idx
	on rbac_audit_log (requestercode);

comment on table rbac_audit_log is 'RBAC mutation audit feed for explorer timeline and admin diagnostics.';
comment on column rbac_audit_log.action is 'RBAC action identifier, for example device.group.add.';
comment on column rbac_audit_log.actor is 'authenticated user that triggered the action.';
comment on column rbac_audit_log.where_path is 'origin route path for the RBAC mutation.';
comment on column rbac_audit_log.how is 'origin category, for example admin-ui, email, or rbac-explorer.';
comment on column rbac_audit_log.what is 'human-readable mutation payload details.';
